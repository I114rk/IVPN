  static String translate(
    String languageCode,
    String source, [
    Map<String, Object?> values = const {},
  ]) {
    final language = languageCode == 'ru'
        ? 'ru'
        : _translations.containsKey(languageCode)
        ? languageCode
        : 'en';
    var result = language == 'ru'
        ? source
        : _translations[language]?[source] ??
              _translations['en']?[source] ??
              source;
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

